def main():
    lr, num_epochs, batch_size = 0.1, 10, 128
    train_iter, test_iter = load_data_fashion_mnist(batch_size, resize=224)
    train_ch6(net, train_iter, test_iter, num_epochs, lr, torch.device('cuda'))

